import type { Blend, Grower, Recipe } from '../api/types.js';
import type { PlaceholderReport } from '../content/placeholder.js';
import { escapeHtml, html, join, raw, type RawHtml } from '../views/html.js';

/**
 * Preview before publish.
 *
 * What this is: the blend page built from the draft record the editor is looking at, in the
 * section order, copy and pending slot behaviour of the consumer page, with the placeholder
 * render contract applied. It answers "what will a customer read when they tap this jar",
 * which is the question preview exists for.
 *
 * What this is not, said plainly rather than discovered later: it is not the byte identical
 * production page. The production page is statically generated by the consumer build in
 * `build/web`, with its own critical CSS, its AVIF and WebP derivatives and its measured
 * byte budget. Preview reads a draft that has not been generated yet, so it cannot be that
 * artifact by definition. Layout is faithful, content is exact, weight is not measured here.
 *
 * The placeholder render contract is reproduced in full, because it is the half of the
 * preview that must not be softer than the real page:
 *
 *   1. A record with placeholder content shows a sticky, undismissable banner.
 *   2. A null placeholder renders its slot with a pending marker rather than collapsing.
 *      A collapsed slot makes the layout smaller than the real page, which makes the
 *      measurement a lie and would force the above the fold check to be re-run the day real
 *      content lands.
 *   3. A control that cannot work yet is disabled and labelled, never hidden and never
 *      pointed somewhere plausible. The reorder button with no cart permalink is the live
 *      example.
 */

const SENTINEL = '[PLACEHOLDER]';
const SECONDARY = 'NOT REAL CONTENT';

/**
 * A value is outlined when it carries the marker, and ALSO when the placeholder report says
 * the field it came from is not real. Both, because the two catch different things: the
 * marker catches a string that travelled from the content package, and the report catches a
 * value that looks entirely plausible and is not, which is the case that actually reaches a
 * customer. The API's own seed data is the live example of the second: it reads as finished
 * copy and carries no marker at all.
 */
function marked(value: string | null | undefined, flagged = false): boolean {
  if (flagged) return true;
  return typeof value === 'string' && (value.includes(SENTINEL) || value.includes(SECONDARY));
}

function textOrPending(value: string | null | undefined, pendingLabel: string, tag = 'p', flagged = false): RawHtml {
  if (value === null || value === undefined || value.trim() === '') {
    return raw(`<${tag} class="pending">${escapeHtml(pendingLabel)}</${tag}>`);
  }
  const cls = marked(value, flagged) ? ' class="is-placeholder"' : '';
  return raw(`<${tag}${cls}>${escapeHtml(value)}</${tag}>`);
}

function imageSlot(alt: string | null | undefined, url: string | null | undefined, label: string, ratio: string): RawHtml {
  if (!url) {
    return html`<div class="slot" style="aspect-ratio:${ratio}"><span>${label} pending</span></div>`;
  }
  return html`<img class="shot" src="${url}" alt="${alt ?? ''}" loading="lazy" style="aspect-ratio:${ratio}" />`;
}

function formatDate(value: string | null | undefined, label: string, flagged = false): RawHtml {
  if (!value) return html`<p class="when pending">${label} date</p>`;
  // A date is a provenance or a food safety claim, and a best before is the one value on
  // this page a customer might act on. If the report says it is not real it is outlined
  // here as loudly as any string.
  return flagged ? html`<p class="when is-placeholder">${value}</p>` : html`<p class="when">${value}</p>`;
}

export interface PreviewInput {
  blend: Blend;
  grower: Grower | null | undefined;
  recipes: Recipe[];
  report: PlaceholderReport;
  /** What the editor is looking at, stated on the page so a screenshot cannot mislead. */
  sourceLabel: string;
}

export function renderPreview(input: PreviewInput): string {
  const { blend, grower, recipes, report } = input;
  const flagged = new Set(
    report.findings.filter((f) => f.isPlaceholder).map((f) => `${f.entity}.${f.path}`),
  );
  const flag = (entity: string, path: string): boolean => flagged.has(`${entity}.${path}`);
  const farm = blend.farm ?? grower?.farm ?? null;
  const story = blend.storyBlocks ?? [];
  const freshness = blend.freshness ?? {};
  const cart = blend.shopify?.cartPermalinkUrl ?? null;

  const body = html`<div class="frame">
    ${report.safeToPublish
      ? ''
      : html`<div class="placeholder-banner" role="note">
          <b>Placeholder content, not for release</b>
          No name, story, location, date or price on this page is real
        </div>`}

    <header class="masthead">
      <p class="brand">Trevean Spice</p>
      <h1${marked(blend.name, flag('blend', 'name')) ? raw(' class="is-placeholder"') : raw('')}>${blend.name}</h1>
      ${textOrPending(blend.tagline, 'tagline pending', 'p', flag('blend', 'tagline'))}
      <p class="origin">
        ${blend.originRegion ?? blend.originCountry ?? raw('<span class="pending">origin pending</span>')}
      </p>
    </header>

    <figure class="hero">${imageSlot(blend.heroImage?.alt, blend.heroImage?.cdnUrl, 'Hero photograph', '1280/955')}</figure>

    <nav class="jump" aria-label="On this page">
      <a href="#story">Story</a>
      <a href="#grower">Grower</a>
      <a href="#freshness">Freshness</a>
      <a href="#recipes">Recipes</a>
      <a class="go" href="#reorder">Reorder</a>
    </nav>

    <section id="story" class="wrap">
      ${story.length === 0
        ? html`<h2 class="pending">origin story heading pending</h2>
            <p class="pending">origin story pending</p>`
        : join(
            story.map((block) =>
              block.type === 'heading'
                ? textOrPending(block.text, 'heading pending', 'h2', flag('blend', 'storyBlocks'))
                : textOrPending(block.text, 'paragraph pending', 'p', flag('blend', 'storyBlocks')),
            ),
          )}
    </section>

    <section id="grower" class="wrap">
      <h2>The grower</h2>
      <div class="grower">
        ${imageSlot(grower?.portrait?.alt, grower?.portrait?.cdnUrl, 'Portrait', '1/1')}
        <div>
          ${textOrPending(grower?.name, 'grower name pending', 'h3', flag('grower', 'name'))}
          ${textOrPending(grower?.farmName, 'farm name pending', 'p', flag('grower', 'farmName'))}
          ${textOrPending(
            grower?.region ?? grower?.country ?? null,
            'grower location pending',
            'p',
            flag('grower', 'region') || flag('grower', 'country'),
          )}
        </div>
      </div>
      ${textOrPending(grower?.bio, 'grower profile pending', 'p', flag('grower', 'bio'))}
      <figure class="map">
        <div class="slot" style="aspect-ratio:640/400"><span>Farm map</span></div>
        <figcaption>
          ${farm
            ? html`<span class="${flag('blend', 'farm.latitude') || flag('grower', 'farm.latitude') ? 'is-placeholder' : ''}"
                >${farm.label ?? 'Farm'} ${farm.latitude.toFixed(3)}, ${farm.longitude.toFixed(3)}</span
              >`
            : html`<span class="pending">coordinates not supplied, so there is no map link</span>`}
        </figcaption>
      </figure>
    </section>

    <section id="freshness" class="wrap">
      <h2>Freshness</h2>
      <ul class="time">
        <li><h3>Harvested</h3>${formatDate(freshness.harvestedOn, 'harvest', flag('blend', 'freshness.harvestedOn'))}</li>
        <li><h3>Blended</h3>${formatDate(freshness.blendedOn, 'blend', flag('blend', 'freshness.blendedOn'))}</li>
        <li><h3>Best before</h3>${formatDate(freshness.bestBefore, 'best before', flag('blend', 'freshness.bestBefore'))}</li>
      </ul>
      <p class="lot">Lot ${freshness.lotLabel ? html`<span class="${marked(freshness.lotLabel, flag('blend', 'freshness.lotLabel')) ? 'is-placeholder' : ''}">${freshness.lotLabel}</span>` : html`<span class="pending">not supplied</span>`}</p>
      ${freshness.note ? html`<p class="note">${freshness.note}</p>` : ''}
    </section>

    <section id="recipes" class="wrap">
      <h2>Recipes with this blend</h2>
      ${recipes.length === 0
        ? html`<p class="pending">no recipes yet, the carousel needs 5 to 10</p>`
        : html`<p class="hint">${recipes.length} recipe${recipes.length === 1 ? '' : 's'}. The carousel needs 5 to 10 to look right on a phone.</p>`}
    </section>
    <div class="wrap">
      <ul class="rail">
        ${join(
          recipes.map(
            (recipe, i) => html`<li class="card">
              ${imageSlot(recipe.image?.alt, recipe.image?.cdnUrl, 'Photograph', '600/450')}
              <p class="num">${i + 1} of ${recipes.length}${recipe.status !== 'published' ? ` (${recipe.status})` : ''}</p>
              ${textOrPending(recipe.title, 'recipe title pending', 'h3', flag('recipe', 'title'))}
              ${textOrPending(recipe.summary, 'recipe summary pending', 'p', flag('recipe', 'summary'))}
              <p class="meta">
                ${recipe.prepMinutes !== null && recipe.prepMinutes !== undefined
                  ? `${(recipe.prepMinutes ?? 0) + (recipe.cookMinutes ?? 0)} min`
                  : 'time not supplied'}
                ${recipe.servings ? ` serves ${recipe.servings}` : ''}
              </p>
            </li>`,
          ),
        )}
      </ul>
    </div>

    <section id="reorder" class="wrap">
      <h2>Running low</h2>
      <div class="buy">
        <p class="price pending">price comes from the Shopify catalog mirror after paint</p>
        ${cart
          ? html`<a class="btn" href="${cart}">Reorder in one tap</a>`
          : html`<span class="btn disabled" aria-disabled="true" role="link">Reorder in one tap</span>
              <p class="note">Disabled because there is no Shopify cart permalink yet. It is labelled rather than hidden or pointed somewhere plausible.</p>`}
      </div>
    </section>

    <footer class="foot">
      <p>Trevean Spice</p>
      <p>This page opens the same way from the NFC tag and from the QR code on the pack. Nothing about it changes between the two.</p>
    </footer>
  </div>`;

  return `<!doctype html>
${html`<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Preview: ${blend.name}</title>
    <link rel="stylesheet" href="/static/preview.css" />
  </head>
  <body>
    ${body}
  </body>
</html>`.value}`;
}
