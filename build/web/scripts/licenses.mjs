#!/usr/bin/env node
/**
 * Generate MANIFEST.md and licenses.json from what is actually installed.
 *
 * The Scope document records a background IP obligation: any pre-existing
 * library or framework reused here must be listed explicitly and licensed to
 * Trevean Spice to run and maintain the product indefinitely, and the list is
 * kept from day one rather than reconstructed at handoff. This is that list,
 * generated from node_modules rather than typed, so it cannot drift from what
 * a build actually pulls in.
 *
 * Run: npm run licenses
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const modules = join(root, 'node_modules');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const PREAMBLE = `# Third-party manifest

**Package:** \`@trevean/consumer-blend-pages\`, the consumer blend pages.
**Purpose:** the explicit list the Scope document, "IP and handoff", requires. Every
pre-existing library reused here, with its licence, kept from day one rather than
reconstructed at handoff.

## The short version

**Nothing third-party reaches a customer's browser. Not one byte.**

The blend page ships hand-written HTML, one inline stylesheet, one 172 byte inline
loader, one first-party enhancement module, and the field beacon vendored verbatim
from the M1 measurement harness. No framework runtime, no polyfill, no analytics,
no font host, no map SDK. That is checked on the built output by
\`npm run verify\` and measured by \`npm run measure\`, and it is the reason the
pre-readable third-party budget of zero is met rather than approximated.

Everything listed below therefore runs at **build time or in development only**.
None of it is a runtime dependency of the deployed site, and none of it needs to
be present on the server, because there is no server: the output is static files.

## What is vendored rather than depended on

| Component | Origin | Licence |
|---|---|---|
| Field beacon (\`public/vendor/harness-beacon/\`) | Serene Labs Inc, M1 deliverable "Measurement harness". Copied verbatim by \`npm run sync:beacon\`, provenance and SHA-256 in \`PROVENANCE.json\`. | Work for hire, owned by Trevean Spice on full payment. Not third-party. |
| Placeholder imagery (\`public/media/\`) | Generated by \`scripts/generate-media.mjs\`. No stock photography, no third-party asset. | Work for hire. Replaced by client photography before release. |
| Icons (\`public/icons/\`) | Generated by the same script. | Work for hire. |
| Placeholder render contract (\`src/styles/placeholder.css\`) | Verbatim copy of \`build/content/render-contract/placeholder.css\` from the content package. \`scripts/postbuild.mjs\` fails the build if the two ever differ. | Work for hire. Deleted with the last placeholder. |

## Two build-time packages used directly rather than only transitively

\`scripts/screenshot.mjs\` drives headless Chrome through \`puppeteer-core\` and
\`chrome-launcher\`, both already installed as dependencies of \`lighthouse\` and both
listed with their licences in the transitive table below. They are used to produce
the section 6.3 evidence and are not declared as direct dependencies, because
adding a second copy of Chrome tooling to the tree to run one screenshot script
would be a worse trade than depending on the copy the measurement runs already
require. If \`lighthouse\` is ever removed, add \`puppeteer-core\` (Apache-2.0) and
\`chrome-launcher\` (Apache-2.0) to \`devDependencies\` in the same commit.

## Fonts

**None are shipped.** The page uses the platform system font stack. The 45 KB
across two WOFF2 files that the byte budget allows for fonts is unspent and is
reserved for the Pulp+Wire brand faces, which must be self-hosted, subset to the
Latin glyphs actually used, preloaded, and paired with a metric-compatible
fallback. A third-party font host is forbidden outright by the Architecture
document, not merely budgeted, and \`npm run verify\` fails the build if one
appears.

`;

function readPackage(dir) {
  try {
    return JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  } catch {
    return null;
  }
}

function licenceOf(meta, dir) {
  if (typeof meta.license === 'string') return meta.license;
  if (meta.license && typeof meta.license.type === 'string') return meta.license.type;
  if (Array.isArray(meta.licenses)) return meta.licenses.map((l) => l.type || l).join(' OR ');
  for (const name of readdirSync(dir)) {
    if (/^licen[cs]e/i.test(name)) return 'see bundled LICENSE file';
  }
  return 'UNKNOWN';
}

function collect(dir, out) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    if (name === '.bin' || name === '.package-lock.json') continue;
    const full = join(dir, name);
    if (!statSync(full).isDirectory()) continue;
    if (name.startsWith('@')) {
      collect(full, out);
      continue;
    }
    const meta = readPackage(full);
    if (!meta || !meta.name) continue;
    out.set(meta.name, {
      name: meta.name,
      version: meta.version,
      license: licenceOf(meta, full),
      homepage: meta.homepage || (meta.repository && (meta.repository.url || meta.repository)) || '',
    });
    collect(join(full, 'node_modules'), out);
  }
  return out;
}

const all = [...collect(modules, new Map()).values()].sort((a, b) => a.name.localeCompare(b.name));
const direct = new Set([...Object.keys(pkg.dependencies || {}), ...Object.keys(pkg.devDependencies || {})]);

const ROLE = {
  next: 'Build time. Renders the markup. Its client runtime is removed by scripts/postbuild.mjs and never shipped.',
  react: 'Build time. Server rendering only.',
  'react-dom': 'Build time. Server rendering only.',
  sharp: 'Build time. Generates the placeholder imagery and enforces the hero byte cap.',
  lighthouse: 'Measurement only. Pinned so the measured numbers are reproducible.',
  typescript: 'Build time. Type checking.',
  '@types/node': 'Development only. Types.',
  '@types/react': 'Development only. Types.',
};

const rows = (list) =>
  list
    .map((d) => `| \`${d.name}\` | ${d.version} | ${d.license} | ${ROLE[d.name] || 'Transitive dependency of a build-time package. Never shipped to a browser.'} |`)
    .join('\n');

const directList = all.filter((d) => direct.has(d.name));
const transitive = all.filter((d) => !direct.has(d.name));

const licenceCounts = new Map();
for (const d of all) licenceCounts.set(d.license, (licenceCounts.get(d.license) || 0) + 1);
const counts = [...licenceCounts.entries()].sort((a, b) => b[1] - a[1]);

/* Copyleft families are the only ones with an obligation worth a sentence.
   Everything else here is permissive and needs no commentary. */
const COPYLEFT = /\b(GPL|LGPL|AGPL|MPL|EPL|CDDL|OSL|CPL)\b/i;
const copyleft = all.filter((d) => COPYLEFT.test(d.license));

const COPYLEFT_NOTES = {
  '@img/sharp':
    'Ships prebuilt libvips binaries under LGPL-3.0-or-later alongside its own Apache-2.0 code. ' +
    'Build time only: it generates placeholder imagery and enforces the hero byte cap, and it is ' +
    'not present in the deployed output. Using an unmodified LGPL library carries no obligation ' +
    'beyond keeping the notices, which the bundled LICENSE files do. Replaceable with any image ' +
    'pipeline if Trevean ever prefers to avoid it.',
  'axe-core':
    'MPL-2.0, file-level copyleft. A dependency of Lighthouse, used only to measure. Never ' +
    'shipped, never modified.',
};

const copyleftSection =
  copyleft.length === 0
    ? 'Every licence above is permissive, with no copyleft obligation.\n'
    : `Every licence above is permissive except the following, which carry a copyleft obligation and are named here rather than buried in a count.\n\n${copyleft
        .map(
          (d) =>
            `- **\`${d.name}\`@${d.version}, ${d.license}.** ${
              COPYLEFT_NOTES[d.name] ||
              COPYLEFT_NOTES[Object.keys(COPYLEFT_NOTES).find((k) => d.name.startsWith(k)) ?? ''] ||
              'Build time or measurement only. Never shipped to a browser and never modified.'
            }`,
        )
        .join('\n')}\n\nNone of them is in the deployed output, so none of them travels with the product a customer loads.\n`;
const nonPermissive = copyleft;

const body = `${PREAMBLE}## Direct dependencies

Declared in \`package.json\`. Versions are pinned exactly, so a rebuilt page is the
same page.

| Package | Version | Licence | Role |
|---|---|---|---|
${rows(directList)}

## Transitive dependencies

Pulled in by the packages above. Every one of them is build time or development
time. None is shipped.

| Package | Version | Licence | Role |
|---|---|---|---|
${rows(transitive)}

## Licence summary

${counts.map(([licence, count]) => `- **${licence}**: ${count} package${count === 1 ? '' : 's'}`).join('\n')}

Total: ${all.length} packages installed.

${copyleftSection}
One attribution licence is worth naming for the same reason: \`caniuse-lite\` is
CC-BY-4.0 browser support data used by the build toolchain. It is data, not code,
it is not shipped, and the attribution travels in its bundled licence file.

Nothing above restricts Trevean Spice from running, modifying, or engaging any
third party to modify this software indefinitely.

## Regenerating this file

\`\`\`
npm run licenses
\`\`\`

It reads \`node_modules\` rather than a hand-kept list, so it cannot drift from
what a build actually pulls in. Regenerate it whenever a dependency changes, and
before any handoff.

Generated ${new Date().toISOString().slice(0, 10)} from an install of the pinned versions above.
`;

writeFileSync(join(root, 'MANIFEST.md'), body, 'utf8');
writeFileSync(
  join(root, 'licenses.json'),
  `${JSON.stringify({ generatedAt: new Date().toISOString(), direct: directList, transitive }, null, 2)}\n`,
  'utf8',
);

console.log(`${all.length} packages: ${directList.length} direct, ${transitive.length} transitive.`);
for (const [licence, count] of counts) console.log(`  ${String(count).padStart(4)}  ${licence}`);
if (nonPermissive.length > 0) {
  console.log('');
  console.log('Licences that are not obviously permissive, review these:');
  for (const d of nonPermissive) console.log(`  ${d.name}@${d.version}  ${d.license}`);
}
console.log('');
console.log('Wrote MANIFEST.md and licenses.json.');
