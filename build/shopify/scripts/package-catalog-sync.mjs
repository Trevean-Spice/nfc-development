#!/usr/bin/env node
/**
 * Build the deployment package for the catalog_sync Lambda.
 *
 * Written Wednesday 14 October 2026. Until then catalog_sync carried the 848 byte
 * infrastructure placeholder (build/infrastructure/modules/compute/placeholder/index.mjs,
 * zipped), because nothing produced a package for it: the API packager's archive exports
 * the Fastify application as index.handler, which a scheduled event cannot drive, and
 * this package had no packager at all.
 *
 * WHAT IT PRODUCES
 *
 *   index.mjs        re-exports `handler` at the archive root, because the compute module
 *                    sets handler = "index.handler" on every pooled function and that value
 *                    is not in its ignore_changes list
 *   package.json     {"type":"module"} so Node reads the compiled .js as ESM
 *   dist/src/**      the compiled package. Nothing else: no tests, no fixtures, and NO
 *                    node_modules, because the package has zero runtime dependencies. The
 *                    AWS SDK is the one that ships inside the nodejs22.x runtime, loaded by
 *                    src/lambda/aws.ts.
 *
 * The archive writer is the deterministic one from build/api/scripts/package-lambda.mjs,
 * copied rather than imported so this directory stays self contained and portable. Same
 * inputs, byte identical archive, same CodeSha256: compare the printed sha256 with the
 * CodeSha256 AWS returns, and that comparison is the proof the deploy landed.
 *
 * After writing the archive it imports the staged index.mjs and checks that `handler` is a
 * function. It does NOT invoke it: an invocation would reach for AWS and Shopify.
 *
 * Usage:
 *   node scripts/package-catalog-sync.mjs
 *   node scripts/package-catalog-sync.mjs --out some/path/catalog-sync.zip
 */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { deflateRawSync } from 'node:zlib';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');

const argv = process.argv.slice(2);
const opt = (name, fallback = null) => {
  const i = argv.indexOf(name);
  return i === -1 ? fallback : argv[i + 1];
};

const STAGE_DIR = path.join(ROOT, '.lambda-build', 'catalog-sync');
const OUT = path.resolve(ROOT, opt('--out', path.join('.lambda-build', 'catalog-sync.zip')));
const ENTRY = 'dist/src/lambda/catalogSyncHandler.js';

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dst = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(src, dst);
    // Source maps and declarations are not needed at runtime and would only change the hash.
    else if (entry.isFile() && entry.name.endsWith('.js')) fs.copyFileSync(src, dst);
  }
}

function walk(dir, base = dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, base, out);
    else if (entry.isFile()) out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out;
}

/* ------------------------------------------------------------ 1. compile TS */

console.log('compiling TypeScript');
fs.rmSync(path.join(ROOT, 'dist'), { recursive: true, force: true });
execFileSync('npm', ['run', 'build'], { cwd: ROOT, stdio: 'inherit', shell: process.platform === 'win32' });

if (!fs.existsSync(path.join(ROOT, ENTRY))) {
  console.error(`REFUSED: ${ENTRY} was not produced by the build. Nothing to package.`);
  process.exit(1);
}

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
if (Object.keys(pkg.dependencies ?? {}).length > 0) {
  console.error('REFUSED: package.json declares runtime dependencies and this packager ships no node_modules.');
  process.exit(1);
}

/* ------------------------------------------------------------ 2. stage code */

console.log('staging application files');
fs.rmSync(STAGE_DIR, { recursive: true, force: true });
copyDir(path.join(ROOT, 'dist', 'src'), path.join(STAGE_DIR, 'dist', 'src'));

fs.writeFileSync(
  path.join(STAGE_DIR, 'index.mjs'),
  [
    '// Generated by scripts/package-catalog-sync.mjs. Not source.',
    '//',
    '// The compute module sets handler = "index.handler" on the catalog_sync function.',
    `export { handler } from './${ENTRY}';`,
    '',
  ].join('\n'),
);
fs.writeFileSync(
  path.join(STAGE_DIR, 'package.json'),
  JSON.stringify({ name: '@trevean/catalog-sync-bundle', private: true, type: 'module' }, null, 2) + '\n',
);

/* --------------------------------------------------- 3. the entry point loads */

const staged = await import(pathToFileURL(path.join(STAGE_DIR, 'index.mjs')).href);
if (typeof staged.handler !== 'function') {
  console.error('REFUSED: the staged index.mjs does not export a handler function.');
  process.exit(1);
}
console.log('staged index.mjs exports handler (loaded, not invoked)');

/* --------------------------------------------------------------- 4. archive */

const entries = walk(STAGE_DIR).sort();
console.log(`archiving ${entries.length} files`);
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, buildZip(STAGE_DIR, entries));

const bytes = fs.statSync(OUT).size;
const sha = createHash('sha256').update(fs.readFileSync(OUT)).digest('base64');
console.log(`\nwrote  ${OUT}`);
console.log(`bytes  ${bytes}`);
console.log(`sha256 ${sha}`);
console.log('\nThat sha256 is the value AWS reports as CodeSha256 once the package is deployed.');

/* ------------------------------------------------------------- the zip file */

// Copied from build/api/scripts/package-lambda.mjs, where the reasoning is written out.
var crcTable;

function crc32(buffer) {
  if (!crcTable) {
    crcTable = new Int32Array(256);
    for (let n = 0; n < 256; n += 1) {
      let c = n;
      for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      crcTable[n] = c;
    }
  }
  let c = -1;
  for (let i = 0; i < buffer.length; i += 1) c = crcTable[(c ^ buffer[i]) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
}

function buildZip(root, names) {
  if (names.length > 0xffff) {
    throw new Error(`${names.length} entries exceeds the 65,535 the non zip64 central directory can address.`);
  }

  // 1980-01-01 00:00:00 in MS-DOS date and time fields, so the archive is deterministic.
  const DOS_TIME = 0;
  const DOS_DATE = 33;

  const locals = [];
  const central = [];
  let offset = 0;

  for (const name of names) {
    const nameBytes = Buffer.from(name, 'utf8');
    const contents = fs.readFileSync(path.join(root, name));
    const deflated = deflateRawSync(contents, { level: 9 });
    const stored = deflated.length >= contents.length;
    const payload = stored ? contents : deflated;
    const method = stored ? 0 : 8;
    const crc = crc32(contents);

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0, 6);
    local.writeUInt16LE(method, 8);
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(payload.length, 18);
    local.writeUInt32LE(contents.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, nameBytes, payload);

    const dir = Buffer.alloc(46);
    dir.writeUInt32LE(0x02014b50, 0);
    dir.writeUInt16LE((3 << 8) | 20, 4);
    dir.writeUInt16LE(20, 6);
    dir.writeUInt16LE(0, 8);
    dir.writeUInt16LE(method, 10);
    dir.writeUInt16LE(DOS_TIME, 12);
    dir.writeUInt16LE(DOS_DATE, 14);
    dir.writeUInt32LE(crc, 16);
    dir.writeUInt32LE(payload.length, 20);
    dir.writeUInt32LE(contents.length, 24);
    dir.writeUInt16LE(nameBytes.length, 28);
    dir.writeUInt16LE(0, 30);
    dir.writeUInt16LE(0, 32);
    dir.writeUInt16LE(0, 34);
    dir.writeUInt16LE(0, 36);
    dir.writeUInt32LE(0o100644 * 0x10000, 38);
    dir.writeUInt32LE(offset, 42);
    central.push(dir, nameBytes);

    offset += local.length + nameBytes.length + payload.length;
  }

  const centralBuffer = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(0, 4);
  end.writeUInt16LE(0, 6);
  end.writeUInt16LE(names.length, 8);
  end.writeUInt16LE(names.length, 10);
  end.writeUInt32LE(centralBuffer.length, 12);
  end.writeUInt32LE(offset, 16);
  end.writeUInt16LE(0, 20);

  return Buffer.concat([...locals, centralBuffer, end]);
}
